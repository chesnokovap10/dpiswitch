// The UI speaks English and Russian. A string is looked up by its English
// text: the templates stay readable, and a string missing a translation
// shows in English rather than as a key (TestTranslations finds them).

func tr(lang, en string) string {
	if lang == "ru" {
		if s, ok := ru[en]; ok {
			return s
		}
	}
	return en
}

